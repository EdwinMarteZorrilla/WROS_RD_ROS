class Nav2Client(Node):
    def __init__(self):
        super().__init__('nav2_client')
        self.client = ActionClient(self, NavigateToPose, 'navigate_to_pose')
        self.stop_pub = self.create_publisher(Twist, '/cmd_vel', 10)

    def send_goal(self, x, y, yaw_deg=0.0):
        goal_msg = NavigateToPose.Goal()
        goal_msg.pose.header.frame_id = 'map'
        goal_msg.pose.header.stamp = self.get_clock().now().to_msg()
        goal_msg.pose.pose.position.x = x
        goal_msg.pose.pose.position.y = y
        yaw = math.radians(yaw_deg)
        goal_msg.pose.pose.orientation.z = math.sin(yaw / 2.0)
        goal_msg.pose.pose.orientation.w = math.cos(yaw / 2.0)
        self.get_logger().info(f" ^=^n  Sending goal  ^f^r ({x:.2f}, {y:.2f}), yaw={yaw_deg:.1f}  ")

        self.client.wait_for_server()
        future = self.client.send_goal_async(goal_msg)
        future.add_done_callback(self.goal_done_callback)

    def goal_done_callback(self, future):
        self.get_logger().info(" ^|^e Navigation goal completed. Stopping robot.")
        stop_msg = Twist()
        self.stop_pub.publish(stop_msg)
        self.get_logger().info(" ^=^{^q Robot stopped  ^`^t holding final heading.")

